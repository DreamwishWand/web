// 08 WEB: My Presets internal 3-domain owner flow, real Chrome; no P1G loaded.
import assert from 'node:assert/strict';
import {chromium} from 'playwright-core';
import {MY_DOMAINS,MY_WAND_VIEWS,myPresetsCopy} from '../src/lib/presets/my-presets-router.mjs';
import {presetsStage1Copy} from '../src/lib/presets/stage1-root.mjs';
const bin=process.env.CHROME_BIN;if(!bin)throw Error('CHROME_BIN_REQUIRED');
const origin=(process.env.MY_PRESETS_E2E_URL||'http://127.0.0.1:4291').replace(/\/$/,'');
const browser=await chromium.launch({executablePath:bin,headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
const ctx=await browser.newContext({viewport:{width:1280,height:850},serviceWorkers:'block',acceptDownloads:false});
const page=await ctx.newPage(),errors=[],requests=[];
page.on('pageerror',e=>errors.push(String(e)));
ctx.on('request',r=>{if(r.method()!=='GET'||new URL(r.url()).origin!==origin)requests.push(r.method()+' '+r.url());});
const fit=async name=>{const m=await page.evaluate(()=>({w:document.documentElement.clientWidth,s:document.documentElement.scrollWidth}));assert.ok(m.s<=m.w+2,name+JSON.stringify(m));};
try{
 await page.goto(origin+'/presets/',{waitUntil:'networkidle',timeout:30000});
 await page.locator('[data-stage1-presets-four-cards]').waitFor();
 assert.equal(await page.locator('[data-preset-child]').count(),4);
 const locales=['en','fr','it','de','es-ES','ja','zh-CN','pt-BR'];
 await page.locator('#site-locale').selectOption('ja');
 await page.waitForFunction(({code,label})=>document.documentElement.dataset.locale===code && document.querySelector('[data-preset-child="wand"] strong')?.textContent?.trim()===label,{code:'ja',label:presetsStage1Copy('ja').wand},{timeout:15000});
 for(const l of locales){
  await page.locator('#site-locale').selectOption(l);
  await page.waitForFunction(({code,label})=>document.documentElement.dataset.locale===code && document.querySelector('[data-preset-child="wand"] strong')?.textContent?.trim()===label,{code:l,label:presetsStage1Copy(l).wand},{timeout:15000});
  await page.locator('[data-preset-child="my"]').click();
  await page.locator('[data-my-domains]').waitFor();
  assert.deepEqual(await page.locator('[data-my-domain]').evaluateAll(x=>x.map(e=>e.getAttribute('data-my-domain'))),MY_DOMAINS);
  assert.equal(await page.locator('[data-my-domain="wand"]').getAttribute('aria-pressed'),'true');
  assert.deepEqual(await page.locator('[data-my-view-button]').evaluateAll(x=>x.map(e=>e.getAttribute('data-my-view-button'))),MY_WAND_VIEWS);
  assert.equal(await page.locator('[data-my-wand-view]').getAttribute('data-my-wand-view'),'created');
  assert.ok((await page.locator('[data-my-wand-view]').innerText()).includes(myPresetsCopy(l).createdUnknown),l+' Created');
  await page.locator('[data-my-view-button="saved"]').click();
  assert.equal(await page.locator('[data-my-wand-view]').getAttribute('data-my-wand-view'),'saved');
  assert.ok((await page.locator('[data-my-wand-view]').innerText()).includes(myPresetsCopy(l).savedUnknown),l+' Saved');
  await page.locator('[data-my-domain="touchOfMagic"]').click();
  assert.equal(await page.locator('[data-my-tom-verified="false"]').count(),1);
  await page.locator('[data-my-domain="inGame"]').click();
  assert.equal(await page.locator('[data-my-save-verified="false"]').count(),1);
  assert.equal(await page.locator('[data-my-current-save="unknown"]').count(),1);
  assert.equal(await page.locator('[data-my-pc-backup="manual"]').count(),1);
  assert.equal(await page.locator('[data-my-creator="unverified"]').count(),1);
  assert.equal(await page.locator('[data-my-pc-local]').count(),0);
  assert.equal(await page.locator('[data-native-writer="off"][data-provider-gate="off"][data-tom-writer="off"]').count(),1);
  await page.locator('.preset-back').click();
  await page.locator('[data-stage1-presets-four-cards]').waitFor();
 }
 console.log('WEB_MY_PRESETS_EIGHT_LOCALES_THREE_INTERNAL_DOMAINS_NO_DATA_AUTHORITY_PASS');
 await page.locator('#site-locale').selectOption('ja');
 await page.locator('[data-preset-child="my"]').click();
 await page.locator('[data-my-domain="inGame"]').click();
 await page.locator('[data-my-open-pc]').focus();
 assert.equal(await page.evaluate(()=>document.activeElement?.getAttribute('data-my-open-pc')),'');
 await page.keyboard.press('Enter');
 await page.locator('[data-my-pc-local] input[type=file]').first().waitFor();
 assert.equal(await page.locator('[data-my-native-writer="off"][data-auto-cloud="off"]').count(),1);
 await page.locator('[data-my-domain="wand"]').click();
 assert.equal(await page.locator('[data-my-pc-local]').count(),1,'PC local inspector not unmounted');
 assert.notEqual(await page.locator('[data-my-pc-local]').getAttribute('hidden'),null);
 await page.locator('[data-my-domain="inGame"]').click();
 assert.ok(await page.locator('[data-my-pc-local] input[type=file]').count()>0);
 console.log('WEB_MY_PRESETS_USER_PC_SELECTION_PRESERVED_NO_AUTO_UPLOAD_PASS');
 await page.setViewportSize({width:320,height:790});await fit('320');
 await page.locator('[data-my-domain="wand"]').focus();
 assert.equal(await page.evaluate(()=>document.activeElement?.getAttribute('data-my-domain')),'wand');
 await page.setViewportSize({width:640,height:790});
 await page.evaluate(()=>{document.documentElement.style.zoom='2';});await fit('200%');
 assert.deepEqual(requests,[],'no external/POST/Cloud request');
 assert.deepEqual(errors,[],'no JS exceptions');
 console.log('WEB_MY_PRESETS_320_ZOOM200_KEYBOARD_NO_PROVIDER_PASS');
}finally{await ctx.close();await browser.close();}
console.log('WEB_MY_PRESETS_ACTUAL_CHROME_PASS');
