// 01A CORE R22 – deterministic *candidate* packaging of generated Rust WASM.
// This does NOT publish to Pages or authorize UI, Writer, Native V3 or Apply.
// Actual signatures must be proved separately, never inferred from SHA-256.
import {readFile,writeFile,mkdir,copyFile,stat} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {join,resolve} from 'node:path';

const root=resolve(import.meta.dirname,'../..');
const generated=join(root,'tests/stage-e/pkg');
const target=join(root,'static/worker-wasm');
const fail=(code)=>{throw Error('R22_WASM_DISTRIBUTION_'+code)};
const sha=b=>createHash('sha256').update(b).digest('hex');
const textCommand=(cmd,args)=>execFileSync(cmd,args,{cwd:root,encoding:'utf8'}).trim();
const expectedHead=process.env.WAND_SOURCE_HEAD;
if(!/^[a-f0-9]{40}$/.test(expectedHead??''))
  fail('SOURCE_HEAD_REQUIRED');
if(textCommand('git',['rev-parse','HEAD'])!==expectedHead)
  fail('SOURCE_HEAD_DIFFERENT_FROM_CHECKOUT');
const features=['indexed-read','worker-wasm'];
const cargo=await readFile(join(root,'crates/ddv-save-core/Cargo.toml'));
const cargoText=cargo.toString('utf8');
for(const required of [
 'worker-wasm = ["dep:wasm-bindgen"]',
 'indexed-read = []',
 'wasm-bindgen = { version = "=0.2.105", optional = true }',
 'private-native-v1 = ["indexed-read"]',
 'private-native-v2 = ["private-native-v1"]'
])if(!cargoText.includes(required))fail('RUST_FEATURE_ABI_CHANGED');
const lock=await readFile(join(root,'crates/ddv-save-core/Cargo.lock'))
  .catch(()=>fail('CARGO_LOCK_NOT_AVAILABLE'));
const toolchain=textCommand('rustc',['--version','--verbose']);
const cargoVersion=textCommand('cargo',['--version']);
const bindgenCli=process.env.WAND_BINDGEN_CLI;
if(!bindgenCli||textCommand(bindgenCli,['--version'])!=='wasm-bindgen 0.2.105')
 fail('BINDGEN_CLI_VERSION');
const names=['ddv_save_core.js','ddv_save_core_bg.wasm'];
const bytes=await Promise.all(names.map(n=>readFile(join(generated,n))));
const [glue,wasm]=bytes;
if(!glue.length||glue.length>2*1024*1024||
   !wasm.length||wasm.length>20*1024*1024)fail('BINARY_LIMIT');
if(wasm.toString('hex',0,4)!=='0061736d')fail('NOT_WASM_BINARY');
const js=glue.toString('utf8');
if(![
 'WorkerWasmSource','issue_saved_diffgrids_typed_cursor',
 'read_saved_diffgrids_typed_page','append_chunk'
].every(n=>js.includes(n)))fail('WASM_GLUE_TYPED_ABI_ABSENT');
if(js.includes('private-native-v2')||js.includes('wand-local-rust-v2-noop'))
 fail('PRIVATE_NATIVE_OR_WRITER_IN_GLUE');
await mkdir(target,{recursive:true});
for(const name of names)await copyFile(join(generated,name),join(target,name));
const statPair=await Promise.all(names.map(n=>stat(join(target,n))));
if(statPair.some((s,i)=>s.size!==bytes[i].length))fail('COPIED_LENGTH_MISMATCH');
const source={
  repository:'DreamwishWand/web',
  commit:expectedHead,
  cargoTomlSha256:sha(cargo),
  cargoLockSha256:sha(lock), // generated dependency lock, not a signed attest
  cargoLockOrigin:'cargo-generated-this-ci-job',
  cargoVersion,toolchain,
  wasmBindgen:'0.2.105',
  wasmTarget:'wasm32-unknown-unknown',
  profile:'release',
  features,
  defaultFeatures:false
};
const manifest={
  contract:'wand.r22.rust-wasm-source-provenance-candidate@1',
  kind:'DEV_READY_PUBLIC_SYNTHETIC_NOT_A_PRODUCT_GATE',
  source,
  assets:{
    js:{path:'ddv_save_core.js',sizeBytes:glue.length,sha256:sha(glue)},
    wasm:{path:'ddv_save_core_bg.wasm',sizeBytes:wasm.length,sha256:sha(wasm)}
  },
  abi:{
    exportClass:'WorkerWasmSource',
    methods:['append_chunk','finish','issue_saved_diffgrids_typed_cursor',
      'read_saved_diffgrids_typed_page','close'],
    maxPageRecords:8,writerAuthorized:false,nativeV3:false
  },
  signature:{
    status:'UNKNOWN',
    verified:false,
    evidence:'GitHub job SOURCE_HEAD + generated lock + tools + byte digests ONLY; no verified signature'
  },
  release:{
    publishedPages:false,
    productConsumerEnabled:false,
    autoUpload:false,
    writerAuthorized:false
  }
};
await writeFile(join(target,'manifest.json'),JSON.stringify(manifest,null,2)+'\n',{flag:'wx'});
await writeFile(join(target,'Cargo.lock'),lock,{flag:'wx'});
const manifestBytes=await readFile(join(target,'manifest.json'));
const publicPins={
  contract:'wand.r22.candidate-pinned-digests@1',
  sourceHead:expectedHead,
  manifestSha256:sha(manifestBytes),manifestSizeBytes:manifestBytes.length,
  jsSha256:sha(glue),wasmSha256:sha(wasm),
  jsSizeBytes:glue.length,wasmSizeBytes:wasm.length,
  sourceProvenanceOnly:true,
  verifiedSignature:false
};
// TEST ONLY: a separately written pin from this CI's generated bytes.
// A public product consumer MUST embed *accepted* independently verified pins;
// fetching a same-origin manifest at runtime is NOT a trust root.
await mkdir(join(root,'tests/wasm-distribution/fixtures'),{recursive:true});
await writeFile(join(root,'tests/wasm-distribution/fixtures/ci-pins.json'),
  JSON.stringify(publicPins,null,2)+'\n',{flag:'wx'});
console.log('R22_PUBLIC_SYNTHETIC_WASM_CANDIDATE_BUILT',{
  sourceHead:expectedHead,wasmBindgen:'0.2.105',rustc:toolchain.split('\n')[0],
  cargoLockSha256:source.cargoLockSha256,manifestSha256:publicPins.manifestSha256,
  jsSha256:publicPins.jsSha256,jsSizeBytes:glue.length,
  wasmSha256:publicPins.wasmSha256,wasmSizeBytes:wasm.length,
  signatureStatus:'UNKNOWN',productionEnabled:false
});
