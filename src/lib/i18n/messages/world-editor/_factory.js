export function machineCodeSegment(code) {
  return String(code ?? '')
    .toLowerCase()
    .replace(/_([a-z0-9])/g, (_, character) => character.toUpperCase());
}

function blockerGroup(code) {
  if (code.includes('BUILDING') || code.includes('HOUSE') || code.includes('STALL') || code.includes('WELL') || code.includes('GARDEN') || code.includes('OFFGRID')) return 'building';
  if (code.includes('ROADFENCE') || code.startsWith('FENCE_') || code.includes('TOPOLOGY_')) return 'roadFence';
  if (code.includes('PLACEMENT') || code.includes('EXACT_BUILD') || code.includes('REPLACEMENT_OR_REMOVAL')) return 'placement';
  if (code.includes('GRID') || code.includes('PLATFORM_CONTRACT') || code.includes('ROUTE_UNRESOLVED') || code.includes('BOUNDS')) return 'route';
  if (code.includes('GEOMETRY') || code.includes('PIVOT')) return 'geometry';
  if (code.includes('COMMIT') || code.includes('PERSISTENT_WRITER')) return 'persistence';
  if (code.includes('FULL_DESIGN')) return 'fullDesign';
  if (code.includes('DRAFT_OPERATION')) return 'draft';
  return 'generic';
}

function coreReasonGroup(code) {
  if (code.includes('PROGRESSION') || code.includes('MISSION') || code.includes('QUEST') || code.includes('SYSTEM_SPAWNED') || code.includes('REFERENCE_SENSITIVE')) return 'progression';
  if (code.includes('BUILDING') || code.includes('HOUSE') || code.includes('STALL') || code.includes('WELL') || code.includes('GARDEN') || code.includes('OFFGRID')) return 'building';
  if (code.includes('ROAD_FENCE')) return 'roadFence';
  if (code.includes('GEOMETRY')) return 'geometry';
  if (code.includes('FURNITURE') || code.includes('WORLD_OBJECT') || code.includes('WORLD_CLASS') || code.includes('GRID_EDIT')) return 'policy';
  return 'generic';
}

export function buildWorldEditorMessages({ copy, blockerGroups, coreReasonGroups, blockerSpecific = {}, coreReasonSpecific = {} }) {
  const messages = { ...copy };
  for (const code of BLOCKER_CODES) {
    const segment = machineCodeSegment(code);
    const group = blockerSpecific[code] ?? blockerGroups[blockerGroup(code)] ?? blockerGroups.generic;
    messages[`worldEditor.blocker.${segment}.title`] = group.title;
    messages[`worldEditor.blocker.${segment}.message`] = group.message;
    messages[`worldEditor.blocker.${segment}.action`] = group.action;
  }
  for (const code of CORE_REASON_CODES) {
    const segment = machineCodeSegment(code);
    messages[`worldEditor.coreReason.${segment}`] =
      coreReasonSpecific[code] ?? coreReasonGroups[coreReasonGroup(code)] ?? coreReasonGroups.generic;
  }
  return Object.freeze(messages);
}

