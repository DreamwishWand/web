/**
 * Read-only WEP artifact proof for an EXISTING Scene revision proposal.
 * Does not reserve media, upload bytes, mint a storage URL, register Blob,
 * publish an immutable revision or authorize any DDV-native writer.
 *
 * Source identity is supplied independently of untrusted artifact metadata.
 * A client claim of ownership / READY media is never server authority.
 */
import { buildPublishEnvelope } from './scene-preset-runtime';
import { sha256Hex } from './preset-community-bridge';
import type { ScenePublicCurrentRead, SceneOwnerReadiness } from './scene-revision-gallery-consumer';
import { SCENE_REVISION_WRITE_BLOCKERS } from './scene-revision-gallery-consumer';

const SWITCH_V125_BID = '52BD625D9B4E0053';

export interface SceneRevisionOfflineSource {
  platform: 'switch';
  gameVersion: '1.25.0';
  buildId: string;
  profileSchema: 624;
  sourceExternallyVerified: true;
}

export interface SceneRevisionArtifactProposal {
  current: ScenePublicCurrentRead;
  readiness: SceneOwnerReadiness;
  source: SceneRevisionOfflineSource;
  artifact: unknown;
  capture: {
    selectionIds: string[];
    includeRoads: boolean;
    includeFences: boolean;
    hasRequiredSubGridDescendants: boolean;
  };
}

export class SceneRevisionIntentError extends Error {
  constructor(code: string) {
    super(code);
    this.name = 'SceneRevisionIntentError';
  }
}

function reject(code: string): never { throw new SceneRevisionIntentError(code); }

const record = (x: unknown): x is Record<string, any> =>
  x !== null && typeof x === 'object' && !Array.isArray(x);

/**
 * A non-uploadable proof, safe for owner preview. No serialized ArtifactBlob
 * bytes or signed URL in the result. Its checksum is of the exact Wand-native
 * JSON UTF-8 bytes generated by the existing WEP envelope builder.
 */
export async function prepareSceneRevisionOfflineIntent(args: SceneRevisionArtifactProposal) {
  const { current, readiness, source, artifact, capture } = args;
  if (!source || source.platform !== 'switch' ||
      source.gameVersion !== '1.25.0' || source.buildId !== SWITCH_V125_BID ||
      source.profileSchema !== 624 || source.sourceExternallyVerified !== true) {
    reject('WEP_SCENE_REVISION_SOURCE_NOT_APPROVED_V125');
  }
  if (!current || !readiness ||
      current.presetArtifactId !== readiness.presetArtifactId ||
      current.workId !== readiness.presetWorkId ||
      current.presetRevisionId !== readiness.currentPresetRevisionId ||
      readiness.ownerEligible !== true ||
      readiness.currentArtifactAvailable !== true ||
      readiness.graphComplete !== false ||
      readiness.dependencyFingerprintIsAtomicFence !== false ||
      readiness.saveRevisionAuthorized !== false ||
      readiness.pairedGalleryPublishAuthorized !== false) {
    reject('WEP_SCENE_REVISION_OWNER_IDENTITY_STALE');
  }
  if (!Array.isArray(capture?.selectionIds) || capture.selectionIds.length === 0 ||
      capture.selectionIds.some(id => typeof id !== 'string' || id.length === 0) ||
      new Set(capture.selectionIds).size !== capture.selectionIds.length ||
      typeof capture.includeRoads !== 'boolean' ||
      typeof capture.includeFences !== 'boolean' ||
      capture.hasRequiredSubGridDescendants !== true) {
    reject('WEP_SCENE_REVISION_CAPTURE_SCOPE_INVALID');
  }
  const proof = buildPublishEnvelope(artifact);
  if (proof.ok !== true || proof.presetType !== 'scene' || !proof.envelope) {
    reject('WEP_SCENE_REVISION_ARTIFACT_VALIDATION_BLOCKED');
  }
  if (!record(artifact) || !record(artifact.source) ||
      artifact.source.gameVersion !== source.gameVersion ||
      artifact.source.platform !== source.platform ||
      !record(artifact.normalization) ||
      artifact.normalization.dependencyClosureIncluded !== true ||
      artifact.normalization.sourceGridIdsRemoved !== true ||
      artifact.normalization.sourceGridObjectIdsRemoved !== true) {
    reject('WEP_SCENE_REVISION_ARTIFACT_SOURCE_OR_CLOSURE_UNVERIFIED');
  }
  if (!record(artifact.requirements) ||
      artifact.requirements.roadTopology !== capture.includeRoads ||
      artifact.requirements.fenceTopology !== capture.includeFences) {
    reject('WEP_SCENE_REVISION_ARTIFACT_NETWORK_SCOPE_MISMATCH');
  }
  const bytes = new TextEncoder().encode(proof.envelope.json);
  if (bytes.byteLength !== proof.envelope.byteSize || bytes.byteLength === 0) {
    reject('WEP_SCENE_REVISION_ARTIFACT_BYTE_SIZE_MISMATCH');
  }
  const checkedBytes = Uint8Array.from(bytes).buffer;
  const checksumSha256 = await sha256Hex(checkedBytes);
  return Object.freeze({
    contract: 'ddv.wep.scene-revision-offline-intent@1' as const,
    source: Object.freeze({ platform:'switch' as const, gameVersion:'1.25.0' as const,
      buildId: SWITCH_V125_BID, profileSchema:624 as const }),
    identity: Object.freeze({
      presetArtifactId: current.presetArtifactId,
      presetWorkId: current.workId,
      currentPresetRevisionId: current.presetRevisionId,
      currentPresetWorkRevisionId: current.workRevisionId,
      associatedGalleryWorkId: current.galleryWorkId,
      currentGalleryWorkRevisionId: current.galleryWorkRevisionId,
      expectedPresetWorkRowVersion: readiness.workRowVersion,
      dependencyFingerprintSha256: readiness.dependencyFingerprintSha256,
      dependencyFingerprintIsAtomicFence: false as const
    }),
    artifact: Object.freeze({
      schemaVersion: proof.envelope.schemaVersion,
      contentType: proof.envelope.contentType,
      byteSize: bytes.byteLength,
      checksumSha256
    }),
    capture: Object.freeze({
      selectedObjectCount: capture.selectionIds.length,
      requiredSubGridDescendantsValidated: true,
      includeRoads: capture.includeRoads,
      includeFences: capture.includeFences
    }),
    // No client-manufactured owner Media/cover IDs. The authoritative READY/CLEAR
    // manifest must be obtained and locked on the server with a verified actor.
    proposedMediaIds: Object.freeze([] as string[]),
    proposedCoverMediaId: null,
    mediaManifestAuthorized: false as const,
    artifactBlobRegistered: false as const,
    atomicRevisionWriterAuthorized: false as const,
    pairedGalleryPublishAuthorized: false as const,
    saveRevisionAuthorized: false as const,
    productApplyAuthorized: false as const,
    blockedReasons: Object.freeze([
      ...SCENE_REVISION_WRITE_BLOCKERS,
      'SCENE_OWNER_READY_MEDIA_MANIFEST_NOT_VERIFIED',
      'SCENE_ARTIFACT_BLOB_REGISTRATION_NOT_ACCEPTED',
      'SCENE_BACKEND_ALL_WRITER_R7_NOT_ACCEPTED',
      'SCENE_SIGNED_STAGING_E2E_NOT_ACCEPTED'
    ])
  });
}
