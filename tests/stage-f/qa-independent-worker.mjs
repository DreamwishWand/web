// 05 QR-C Task W-CORE-004+W-LOCAL-019 — independent Stage F scoped actual Chrome/WASM QA.
// Genuine Rust wasm-bindgen Worker, PUBLIC SYNTHETIC P1G only, never private Save or product Writer.
// Source PR761 original 8 paths are immutable; this QA worker is not merged into main.
import init,{WorkerWasmSource} from '../stage-e/pkg/ddv_save_core.js';
import {createP1gRustWorkerReadOnlyBridge} from
  '../../src/lib/ddv/core/save/p1g-rust-worker-readonly-bridge.mjs';

const BUILD=Object.freeze({platform:'steam-windows',buildKind:'steam-full-version',
  buildId:'releases_1.25-v1.25.3-44-g0b41250d9ac0-incremental-22',
  schema:626,externallyConfirmed:true});
const scope=r=>({sessionId:r.sessionId,revision:r.revision,
  indexGeneration:r.indexGeneration,decodedSha256:r.decodedSha256});
const check=(ok,label)=>{if(!ok)throw Error('INDEPENDENT_STAGEF_'+label)};
const deny=async(task,label,match)=>{
  try{await task()}catch(e){
    if(match)check(String(e?.message||e).includes(match),'UNEXPECTED_DENIAL_'+label);
    return true;
  }
  throw Error('INDEPENDENT_STAGEF_ACCEPTED_'+label);
};
const factory=()=>Promise.resolve({WorkerWasmSource});
const hexdigest=async a=>Array.from(new Uint8Array(
  await crypto.subtle.digest('SHA-256',a)),
  x=>x.toString(16).padStart(2,'0')).join('');
const make=()=>createP1gRustWorkerReadOnlyBridge(factory);

async function run(){
  check(typeof document==='undefined','NOT_MODULE_WORKER');
  check(typeof crypto?.getRandomValues==='function'&&
    typeof crypto?.subtle?.digest==='function','NO_WORKER_CRYPTO');
  const start=performance.now();
  await init(new URL('../stage-e/pkg/ddv_save_core_bg.wasm',import.meta.url));
  const wasmMs=Math.round(performance.now()-start);
  check(typeof WorkerWasmSource==='function','NO_REAL_WASM_CLASS');

  // All input is generated by the Source fixture helper on the ephemeral CI runner.
  const [cipherResp,expectedResp]=await Promise.all([
    fetch('./fixtures/synthetic626.p1g',{cache:'no-store'}),
    fetch('./fixtures/expected.json',{cache:'no-store'})
  ]);
  check(cipherResp.ok&&expectedResp.ok,'SYNTHETIC_FIXTURE_MISSING');
  const original=new Uint8Array(await cipherResp.arrayBuffer());
  const expected=await expectedResp.json();
  check(expected.syntheticOnly===true&&expected.sourceBytes===original.byteLength,
    'SYNTHETIC_FIXTURE_PROVENANCE');
  check(original.length>0&&original.length<1024*1024 &&
    expected.decodedBytes>1024*1024,'NOT_MULTICHUNK_UNICODE_TEST');
  const cipherHash=await hexdigest(original);

  const bridge=make();
  const started=performance.now();
  const r=await bridge.openEncrypted({build:BUILD,encryptedBytes:original});
  const openMs=Math.round(performance.now()-started);
  check(r.decodedSha256===expected.decodedSha256 &&
    r.fullDocumentJsonValidated===true && r.decodedByExistingP1gCodec===true,
    'CODEC_RUST_SOURCE_SHA_V1');
  check(r.externalPhysicalBuildVerified===false&&r.productReadAccepted===false&&
    r.writerAuthorized===false&&r.editedCopyAuthorized===false&&
    r.applyAuthorized===false&&r.allDomainReferencesVerified===false,
    'WRITER_OR_PHYSICAL_BUILD_MISCLAIM');
  check(!('jsonText' in r)&&!('encryptedBytes' in r)&&
    !('rawValue' in r),'RAW_SAVE_RECEIPT_LEAK');
  check(await hexdigest(original)===cipherHash,'CALLER_CIPHERTEXT_MUTATED');

  const s=scope(r),version=bridge.readCoreVersion(s);
  check(version.coreOwnedReadset==='/GameInfo/Version' &&
    version.writerAuthorized===false,'CORE_WITNESS_BAD');
  const cap=bridge.getCapabilities();
  check(cap.p1gWorkerReadOnlyBridge===true &&
    cap.productReadAccepted===false && cap.canReadTypedMetadataInProduct===false &&
    cap.canExportEditedCopy===false && cap.canApply===false,
    'PRODUCTION_GATE_ENABLED');

  const keys=[];let cursor=bridge.issueTypedCursor(s,'player').cursor;
  const pagestart=performance.now();
  for(const count of [16,16,1]){
    check(typeof cursor==='string'&&cursor.length===32&&
      !/^0+$/.test(cursor),'ZERO_CURSOR');
    const page=bridge.readTypedPage(s,cursor);
    check(page.fields.length===count&&page.writerAuthorized===false&&
      page.productReadAccepted===false&&page.completeAllDomains===false,
      'UNBOUNDED_OR_GRANTED_PAGE');
    keys.push(...page.fields.map(f=>f.key));
    const old=cursor;cursor=page.nextCursor;
    await deny(()=>bridge.readTypedPage(s,old),'REPLAY','PRODUCT_WORKER_CURSOR_UNKNOWN_OR_CONSUMED');
  }
  const pageMs=Math.round(performance.now()-pagestart);
  check(keys.length===33&&keys[0]==='field_000'&&
    keys.at(-1)==='field_032'&&cursor===null,'PLAYER_PAGE_16_16_1');
  const world=bridge.issueTypedCursor(s,'world');
  const wpage=bridge.readTypedPage(s,world.cursor);
  check(wpage.fields.length===2 && wpage.nextCursor===null,'WORLD_TYPED_PAGE');
  await deny(()=>bridge.issueTypedCursor(s,'../../Private'),'FORGED_DOMAIN',
    'PRODUCT_WORKER_DOMAIN_DENIED');
  await deny(()=>bridge.readCoreVersion({...s,uiReadset:'/Secrets'}),'FORGED_SCOPE',
    'PRODUCT_WORKER_SCOPE_CAS');
  await deny(()=>bridge.readCoreVersion({...s,indexGeneration:2}),'STALE_INDEX',
    'PRODUCT_WORKER_SCOPE_CAS');

  // A then B for SAME ciphertext: previous Session and cursor must be revoked.
  const oldSession=s.sessionId;
  const future=bridge.issueTypedCursor(s,'player');
  const updated=await bridge.openEncrypted({build:BUILD,encryptedBytes:original});
  check(updated.sessionId!==oldSession&&updated.decodedSha256===s.decodedSha256,
    'SAME_INPUT_REOPEN_SESSION_REUSE');
  await deny(()=>bridge.readTypedPage(s,future.cursor),'STALE_SESSION',
    'PRODUCT_WORKER_SCOPE_CAS');
  await deny(()=>bridge.readTypedPage(scope(updated),future.cursor),
    'STALE_CURSOR_NEW_SESSION','PRODUCT_WORKER_CURSOR_UNKNOWN_OR_CONSUMED');
  check(await hexdigest(original)===cipherHash,'REOPEN_MUTATED_ORIGINAL');

  // Delayed P1G AES/ZIP decode A MUST NOT resurrect after immediately requested B.
  const racer=make();
  const openA=racer.openEncrypted({build:BUILD,encryptedBytes:original});
  const openB=racer.openEncrypted({build:BUILD,encryptedBytes:original});
  const race=await Promise.allSettled([openA,openB]);
  check(race[0].status==='rejected'&&
    String(race[0].reason?.message).includes('P1G_WORKER_OPEN_REVOKED')&&
    race[1].status==='fulfilled','SIMULTANEOUS_AB_RACE_NOT_REVOKED');
  check(racer.getReceipt()?.sessionId===race[1].value.sessionId &&
    racer.getReceipt()?.writerAuthorized===false,'RACE_WRONG_WINNER');
  racer.close();check(racer.getReceipt()===null,'RACE_CLOSE_RETAINED_SESSION');

  bridge.close();
  await deny(()=>bridge.issueTypedCursor(scope(updated),'player'),
    'CLOSED_SESSION','PRODUCT_WORKER_SESSION_CLOSED');
  check(bridge.close().closed===true&&bridge.getReceipt()===null,
    'IDEMPOTENT_CLOSE');

  const bad=make();
  await deny(()=>bad.openEncrypted({build:{...BUILD,buildId:'unknown'},
    encryptedBytes:original}),'UNKNOWN_STEAM_BUILD','PRODUCT_WORKER_BUILD_NOT_VERIFIED');
  await deny(()=>bad.openEncrypted({build:{...BUILD,platform:'switch'},
    encryptedBytes:original}),'STEAM_SWITCH_MISMATCH');
  await deny(()=>bad.openEncrypted({build:{...BUILD,schema:624},
    encryptedBytes:original}),'SCHEMA_624','P1G_WORKER_EXTERNAL_BUILD_REQUIRED');
  await deny(()=>bad.openEncrypted({build:{...BUILD,externallyConfirmed:false},
    encryptedBytes:original}),'UNATTESTED_CANDIDATE','P1G_WORKER_EXTERNAL_BUILD_REQUIRED');
  await deny(()=>bad.openEncrypted({build:BUILD,encryptedBytes:original,
    entropy:'untrusted'}),'UI_ENTROPY','P1G_WORKER_INPUT_DENIED');
  await deny(()=>bad.openEncrypted({build:BUILD,
    encryptedBytes:original.slice(0,-1)}),'TRUNCATED_CIPHER');
  check(bad.getReceipt()===null,'MALFORMED_SOURCE_CREATED_SESSION');

  // Parent page gets ONLY bounded scalar summary, never ciphertext/decoded JSON.
  const summary={
    result:'SYNTHETIC_P1G_TO_REAL_RUST_WORKER_PASS',
    chromeModuleWorker:true,realGeneratedWasm:true,existingP1gCodec:true,
    singleRustSession:true,decodedSHACompared:true,staleScopeDenied:true,
    ABRevocation:true,malformedCiphertextDenied:true,badBuildDenied:true,
    extraEntropyDenied:true,noDecodedJsonPostedToParent:true,
    wasmMs,openMs,pageMs,encryptedBytes:original.length,
    decodedBytes:expected.decodedBytes,playerFields:keys.length,
    worldFields:wpage.fields.length,writerAuthorized:false,
    productReadAccepted:false,realOwnerPrivateSave:false,nativeV3:false,deviceV4:false
  };
  const json=JSON.stringify(summary);
  check(json.length<1024 && !json.includes(s.decodedSha256) &&
    !json.includes('UnknownFuture') && !json.includes('field_') &&
    !json.includes(cipherHash),'NON_SENSITIVE_SUMMARY_ONLY');
  return summary;
}
self.onmessage=async evt=>{
  if(evt.data?.kind!=='RUN_STAGE_F')return;
  try{self.postMessage({status:'PASS',summary:await run()})}
  catch(e){self.postMessage({status:'FAIL',error:String(e?.message||e).slice(0,300)})}
};
